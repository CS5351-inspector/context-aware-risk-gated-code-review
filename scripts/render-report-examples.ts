import fs from 'node:fs';
import path from 'node:path';
import { createReportExamples } from './report-example-data.js';

async function main() {
  const outputRoot = process.env.INSPECTOR_REPORT_EXAMPLE_DIR || 'docs';
  const standaloneDir = path.join(outputRoot, 'report-examples');
  const { examples } = await createReportExamples();
  fs.mkdirSync(standaloneDir, { recursive: true });
  for (const example of examples) {
    fs.writeFileSync(path.join(standaloneDir, `${example.slug}.md`), example.report + '\n');
  }
  const section = (example: typeof examples[number]) => [
    `## ${example.title}`,
    '',
    example.description,
    '',
    `[Standalone report](report-examples/${example.slug}.md)`,
    '',
    '```md', example.report, '```',
  ].join('\n');
  const document = [
    '# Inspector report examples',
    '',
    'Generated by `npm run examples:report`. These synthetic inputs demonstrate rendering and guarded publication behavior; they are not real model, GitHub publication, or acceptance evidence.',
    'The normal, partial, and failed examples use the same reviewed SHA so their status, coverage, omissions, evidence, resources, and next action can be compared.',
    'Each example is also written as an independent Markdown file. `npm run verify:report` regenerates all four files in an isolated directory, compares them byte-for-byte with the committed copies, and checks the actual publication-failure path.',
    '',
    ...examples.flatMap(example => [section(example), '']),
  ].join('\n');
  fs.writeFileSync(path.join(outputRoot, 'SPRINT2_REPORT_EXAMPLES.md'), document);
}

main().catch(error => {
  console.error(error instanceof Error ? error.message : 'Could not render report examples');
  process.exitCode = 1;
});
